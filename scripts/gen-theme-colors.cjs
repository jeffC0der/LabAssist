// Run from the project root: node scripts/gen-theme-colors.cjs
// Generates app/theme-colors.css: every palette shade as an "r g b" CSS variable.
// Dark (default) = Tailwind's original colors. Light = shades flipped so dark surfaces become light
// and light text becomes dark; accents keep their mid tones (buttons stay saturated with white text).
const fs = require('fs');
const colors = require('tailwindcss/colors');

const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const ACCENTS = ['indigo', 'emerald', 'amber', 'rose', 'cyan', 'violet', 'red', 'blue', 'purple', 'orange', 'sky', 'lime', 'green', 'yellow', 'teal', 'pink', 'fuchsia'];

const rgb = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
};
const mix = (a, b) => rgb(a).map((v, i) => Math.round((v + rgb(b)[i]) / 2));
const fmt = (arr) => arr.join(' ');

// slate: full flip (also the in-between shades the app uses: 750, 850)
const slateDark = Object.fromEntries(SHADES.map((s) => [s, rgb(colors.slate[s])]));
slateDark[750] = mix(colors.slate[700], colors.slate[800]);
slateDark[850] = mix(colors.slate[800], colors.slate[900]);
const slateFlip = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 500, 600: 400, 700: 300, 750: 250, 800: 200, 850: 150, 900: 100, 950: 50 };
// Light surfaces get a faint indigo tint so the theme keeps its blue-violet character (not neutral gray)
const tint = (rgbArr, amount) => rgbArr.map((v, i) => Math.round(v + (rgb(colors.indigo[100])[i] - v) * amount));
const TINT = { 50: 0.25, 100: 0.3, 150: 0.3, 200: 0.25, 250: 0.2, 300: 0.15 };
const slateLightAtRaw = (s) => {
  if (s === 250) return mix(colors.slate[200], colors.slate[300]);
  if (s === 150) return mix(colors.slate[100], colors.slate[200]);
  return rgb(colors.slate[s]);
};
const slateLightAt = (s) => (TINT[s] ? tint(slateLightAtRaw(s), TINT[s]) : slateLightAtRaw(s));

// Text tones stay vivid (300 → 700, 400 → 600) and dark tints become visible pastel washes (900/950 → 200/100)
const accentFlip = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 500, 600: 600, 700: 700, 800: 200, 900: 200, 950: 100 };

let dark = ':root {\n  color-scheme: dark;\n';
let light = 'html.light {\n  color-scheme: light;\n';
for (const s of Object.keys(slateFlip).map(Number)) {
  dark += `  --c-slate-${s}: ${fmt(slateDark[s])};\n`;
  light += `  --c-slate-${s}: ${fmt(slateLightAt(slateFlip[s]))};\n`;
}
for (const name of ACCENTS) {
  for (const s of SHADES) {
    dark += `  --c-${name}-${s}: ${fmt(rgb(colors[name][s]))};\n`;
    light += `  --c-${name}-${s}: ${fmt(rgb(colors[name][accentFlip[s]]))};\n`;
  }
}
dark += '}\n';
light += '}\n';

const header = `/* Generated by scripts/gen-theme-colors.cjs: Tailwind palettes as CSS variables so the whole app can switch
   between Dark (original) and Light. Dark keeps Tailwind's colors; html.light flips the shades. */\n`;
fs.writeFileSync('app/theme-colors.css', header + dark + '\n' + light);
console.log('wrote app/theme-colors.css');
console.log(JSON.stringify({ slate: [...Object.keys(slateFlip)], accents: ACCENTS }));
